// รูปบนการ์ดผลลัพธ์: ตั้งชื่อไฟล์ใน ./asset ให้ตรงกับ id เช่น tulip.png ระบบจะหยิบมาใช้เอง
const RESULT_IMAGES = import.meta.glob<string>(
  "./asset/*.{png,jpg,jpeg,webp,gif}",
  {
    eager: true,
    import: "default",
  },
);

export function resultImageFor(id: string): string | undefined {
  const path = Object.keys(RESULT_IMAGES).find(
    (p) => p.replace(/^.*\/|\.\w+$/g, "") === id,
  );
  return path && RESULT_IMAGES[path];
}
